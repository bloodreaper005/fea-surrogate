"""Publish a swept dataset to the Hugging Face Hub as a private dataset.

    hf auth login                  # once, stores the token
    python -m fea_surrogate.generate.publish --data data/sweep --repo fea-sweep

The token is read from `HF_TOKEN` if set, otherwise from the stored login. It is
never taken as an argument, so it cannot end up in a shell history or a
transcript. An owner-less `--repo` is resolved against whoever is logged in.

The card is generated from the manifest rather than written by hand, so what it
claims about the data is what the data says. In particular it carries
`set_sha256`, which is the digest a calibration record has to cite: a coverage
figure is a claim the consumer stores and cannot verify, and it is only
meaningful if the set it was measured on can be named.
"""

from __future__ import annotations

import argparse
import json
import os
from pathlib import Path
from typing import Any


CARD_TEMPLATE = """---
license: apache-2.0
tags:
  - finite-element-method
  - stress-analysis
  - graph-neural-networks
  - mechanical-engineering
---

# {repo}

Linear elastic FEA over parametric mechanical components, generated by
[`fea-surrogate`](https://github.com/{owner}/fea-surrogate) for training a
stress-screening surrogate.

**{samples} samples**, `set_sha256` `{digest}`.

## Families

{family_table}

## What is in a shard

Samples are concatenated with offset arrays rather than stored ragged. Each
`shard-NNNN.npz` holds:

| key | shape | meaning |
| --- | --- | --- |
| `x` | (sum N, 13) | node features, see below |
| `y_nodal` | (sum N,) | von Mises averaged onto nodes — the field |
| `tetrahedra` | (sum M, 4) | offset into the shard; subtract `node_offsets[i]` |
| `node_offsets`, `tet_offsets` | (S+1,) | sample boundaries |
| `tau` | (S,) | **the training target**: dimensionless critical-distance von Mises (volume-averaged, see below) |
| `tau_peak` | (S,) | the same scaling applied to `peak`; kept for comparison, not the target |
| `peak` | (S,) | peak von Mises from unaveraged element stresses, in MPa |
| `poisson`, `force_n`, `length_mm`, `family` | (S,) | per-sample scalars |

Node features are `[pos(3) | sdf(1) | normal(3) | is_fixed(1) | is_loaded(1) |
load_dir(3) | poisson(1)]`.

## Two things that make this different from existing FEA datasets

**Load location is in the features.** `is_loaded` and `load_dir` say where the
load lands. A dataset that encodes only load *magnitude* cannot be used to
answer "what is the stress in this part, under this load, applied here", because
samples differing only in load placement have identical inputs and different
answers; the best any model can do there is predict their mean.

**The target is dimensionless and averaged.** `tau = sigma * L^2 / F`, with
`L` the bounding-box diagonal and `sigma` the critical-distance stress: element
von Mises averaged by volume over every element whose centroid lies within one
thin dimension (`min(smallest bounding-box extent, 2V/A)`) of the hottest
element. It is not the peak. An elastic peak at a re-entrant corner is singular
and keeps rising as the mesh is refined, so it states the mesh rather than the
part; the average does not. In bending it averages across the section and so
reads well below the surface stress.

In linear elasticity the stress field is independent of Young's modulus — E
only sets displacement — and scales as F/L². So a model fitted here transfers across scale, load and stiffness. Recover stress with
`sigma[MPa] = tau * F[N] / L[mm]^2`.

Poisson's ratio does *not* cancel, because the held faces are displacement
boundary conditions. It is swept over {poisson_range} and is a feature.

## Limitations

- Constant-strain tetrahedra (P1). Against a closed-form cantilever the element
  peak reaches ~0.92 of the analytical answer at the meshing used here, while
  the beam's bending away from the root is under-read, because P1 is stiff in
  bending. `tau` is a consistent training signal on this solver and mesh rule,
  not a certified value.
- One load case per sample: a single uniform traction over the tagged faces.
  Not contact, not moving loads, not distributed pressure fields.
- Linear elastic only. No plasticity, no large displacement, no buckling.
- Geometry is parametric and synthetic. It spans the *modes* real components
  load in, not the shapes of any particular product.

## Reading it

```python
from fea_surrogate.generate.dataset import SweptDataset

data = SweptDataset("path/to/sweep")
print(len(data), data.set_sha256)
for sample in data:
    sample.x, sample.y_nodal, sample.tau, sample.edge_index()
```

## Provenance

Generated with seed `{seed}`, {rejected} draws rejected by the mesher or solver
and counted rather than resampled. Generated at {generated_at}.
"""


def build_card(manifest: dict[str, Any], repo: str) -> str:
    rows = "\n".join(
        f"| `{name}` | {count} |"
        for name, count in sorted(manifest.get("by_family", {}).items())
    )
    return CARD_TEMPLATE.format(
        repo=repo,
        owner=repo.split("/")[0],
        samples=manifest.get("samples", 0),
        digest=manifest.get("set_sha256", ""),
        family_table="| family | samples |\n| --- | --- |\n" + rows,
        poisson_range="0.27–0.42",
        seed=manifest.get("seed", 0),
        rejected=manifest.get("rejected", 0),
        generated_at=manifest.get("generated_at", "unknown"),
    )


def _resolve(repo: str, api) -> str:
    """Let `--repo name` mean `<whoever is logged in>/name`."""
    if "/" in repo:
        return repo
    try:
        owner = api.whoami()["name"]
    except Exception as exc:
        raise SystemExit(f"cannot resolve an owner for {repo!r}: {exc}") from None
    return f"{owner}/{repo}"


def publish(data_dir: Path, repo: str, *, private: bool = True) -> str:
    from huggingface_hub import HfApi

    # Environment first, then the stored login. Never an argument: a token
    # passed on a command line lands in shell history.
    token = os.environ.get("HF_TOKEN", "").strip() or None
    api = HfApi(token=token)
    try:
        api.whoami()
    except Exception:
        raise SystemExit(
            "not authenticated. Run `hf auth login` with a write token from "
            "https://huggingface.co/settings/tokens, or set HF_TOKEN. "
            "(`huggingface-cli login` is deprecated and no longer works.)"
        ) from None

    manifest_path = data_dir / "manifest.json"
    if not manifest_path.is_file():
        raise SystemExit(f"no manifest.json in {data_dir}; run the sweep first")
    manifest = json.loads(manifest_path.read_text(encoding="utf-8"))

    repo = _resolve(repo, api)
    card = data_dir / "README.md"
    card.write_text(build_card(manifest, repo), encoding="utf-8")

    api.create_repo(repo, repo_type="dataset", private=private, exist_ok=True)
    api.upload_folder(
        repo_id=repo,
        folder_path=str(data_dir),
        repo_type="dataset",
        commit_message=(
            f"{manifest['samples']} samples, "
            f"set_sha256 {manifest['set_sha256'][:12]}"
        ),
    )
    return f"https://huggingface.co/datasets/{repo}"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--data", type=Path, required=True)
    parser.add_argument("--repo", required=True, help="owner/name")
    parser.add_argument("--public", action="store_true")
    args = parser.parse_args(argv)

    url = publish(args.data, args.repo, private=not args.public)
    print(f"published {url}")


if __name__ == "__main__":
    main()
